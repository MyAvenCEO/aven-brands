/**
 * THE NAME-CLAIM CARD, split at the seam where behaviour actually starts.
 *
 * The card is one form with one field in it, and almost none of it is the
 * field: an eyebrow, a headline, a sentence, four benefit bullets, a price
 * block and an early-adopter footer bar are all facts of the build. They
 * render here as ViewDefs, at build, and the component places three strings
 * around the one row that a reader can type into.
 *
 * WHY THE FIELD IS NOT HERE, measured rather than assumed. An island would
 * need three things this engine does not offer:
 *
 *   - The submit button is disabled until the typed name yields a usable slug,
 *     and the slug is `toLowerCase`, a character filter and a truncation of
 *     what was typed. Expressions in a view are PATH LOOKUPS — `$open`,
 *     `$props.label` — with no negation and no string transforms, so neither
 *     the slug nor its emptiness can be written in a view.
 *   - Tracking the field in island state re-renders the island on every
 *     keystroke, and `Island` restores focus by path but NOT the selection
 *     range (only `VibeEngine` captures `selectionStart`/`selectionEnd`). The
 *     caret would jump to the end of the site's single most important input on
 *     every character.
 *   - Dropping the state to avoid that drops the `disabled` attribute with it.
 *     A CSS stand-in (`:has(input:placeholder-shown)`) dims the button without
 *     disabling it, so it stays focusable and still announces as available —
 *     an accessibility regression traded for a smaller diff.
 *
 * So the chrome is configuration and the field is code, which is the honest
 * line. When a view can express a derived value, the whole card follows.
 *
 * THE EYEBROW AND THE HEADLINE STAY IN THE TEMPLATE, and not by taste. The
 * utility layer is generated by scanning the source: a class written in a
 * `class=` attribute is CERTAIN, a class that merely looks like one inside a
 * `.ts` file is a CANDIDATE, and `generate()` emits certain rules first and
 * candidate rules after — after the certain MEDIA BLOCKS included. So a base
 * utility that leaves the last `class=` attribute on the site starts winning
 * over its own `sm:` variant, everywhere, silently.
 *
 * This card held the last class attribute carrying the 2xl text size anywhere
 * in the app. Moving the headline here dropped it into the candidate tier, and
 * its rule (font-size 1.5rem, line-height 1.33333) began overriding the sm
 * variant of the 3xl size (1.875rem, line-height 1.2) — which is still
 * certain, from `Widerruf.svelte`. Measured on two builds made back to back:
 * at 700px the headline rendered 24px where it had rendered 30px, and the
 * whole card grew 3.2px. That is not local to this card either — every
 * heading on the site pairing those two sizes would have flipped.
 *
 * So the headline keeps its class attribute until the pipeline stops letting
 * file type decide cascade order. Everything with no such pairing moves.
 *
 * THE INLINE VARIANT IS GONE. Every one of the five surfaces that mounts this
 * card asks for the banner, and the inline variant was not merely unused: its
 * footer bar cancelled the BANNER padding with negative margins (`-mx-5 -mb-9
 * sm:-mx-10 sm:-mb-11`) while the inline box is padded `px-5 py-7 sm:px-8
 * sm:py-8`, so the bar never lined up with the box it was clipped to.
 *
 * Prose lives in block comments only — the utility scanner reads line comments
 * and one apostrophe in one swallows the class candidates (see footer.ts).
 */
